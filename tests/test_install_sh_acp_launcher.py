SLICK_AGENT_BLOCK = re.compile(
    r'(rm -f "\$command_link_dir/slick-agent".*?'
    r'log_success "Installed slick-agent launcher[^\n]*\n)',
    re.S,
)


def _extract_slick_agent_shim_block() -> str:
    match = SLICK_AGENT_BLOCK.search(INSTALL_SH.read_text(encoding="utf-8"))
    assert match, (
        "could not locate the slick-agent launcher block in scripts/install.sh — "
        "if it was renamed, update this test with it"
    )
    return match.group(1)


def _run_slick_agent_block(tmp_path: Path, use_venv: str) -> Path | None:
    """Execute the extracted slick-agent block with the env vars setup_path() sets."""
    if use_venv == "false":
        # --no-venv: slick-agent is NOT installed by this block (handled
        # elsewhere), so there's nothing to test here.
        return None

    command_link_dir = tmp_path / "local_bin"
    command_link_dir.mkdir()
    slick_bin = tmp_path / "venv" / "bin" / "python"
    slick_bin.parent.mkdir(parents=True)
    slick_bin.write_text("#!/bin/sh\n", encoding="utf-8")
    install_dir = tmp_path / "install"
    install_dir.mkdir()

    script = (
        "set -e\n"
        f"SLICK_BIN={slick_bin}\n"
        f"INSTALL_DIR={install_dir}\n"
        f"command_link_dir={command_link_dir}\n"
        f"command_link_display_dir={command_link_dir}\n"
        f"USE_VENV={use_venv}\n"
        "log_success(){ :; }\n" + _extract_slick_agent_shim_block()
    )
    result = subprocess.run(
        ["bash", "-c", script],
        capture_output=True,
        text=True,
        cwd=tmp_path,
    )
    assert result.returncode == 0, (
        f"slick-agent shim block failed:\nstdout={result.stdout}\nstderr={result.stderr}"
    )
    return command_link_dir / "slick-agent"


def test_venv_install_writes_executable_slick_agent_launcher(tmp_path):
    """venv install must write a user-executable slick-agent launcher."""
    shim = _run_slick_agent_block(tmp_path, "true")
    assert shim is not None
    assert shim.is_file()
    assert shim.stat().st_mode & stat.S_IXUSR, "launcher must be user-executable"

    text = shim.read_text(encoding="utf-8")
    assert "unset PYTHONPATH" in text
    assert "unset PYTHONHOME" in text
    assert "run_agent.py" in text, "slick-agent must dispatch to run_agent.py"


def test_slick_agent_launcher_cleanup_on_uninstall(tmp_path):
    """uninstall.remove_wrapper_script() must remove slick-agent alongside
    slick and slick-acp."""
    from slick_cli.uninstall import remove_wrapper_script

    # Simulate a slick-agent wrapper in the user-local location
    local_shim = tmp_path / ".local" / "bin" / "slick-agent"
    local_shim.parent.mkdir(parents=True)
    local_shim.write_text("#!/usr/bin/env bash\nexec slick-agent\n", encoding="utf-8")

    with patch.object(Path, "home", return_value=tmp_path):
        removed = remove_wrapper_script()

    assert local_shim in removed, "local slick-agent wrapper must be removed"
